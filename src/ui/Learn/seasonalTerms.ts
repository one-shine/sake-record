// 季節の呼び名（新酒・ひやおろし など）。
//
// ## この表の性質（`seishuMeisho.ts` と決定的に違う）
//
// **これは法令の逐語ではない。** 酒屋と蔵が使う**慣習の呼び名**で、告示にも酒税法にも
// この形の定義は無い（正確には「無いと断定できるだけの確認をしていない」）。
// だから画面では**「慣習」のバッジを付けて、告示由来の表と見た目で割る**。
// 割らずに並べると、隣にある告示の逐語表まで同じ根拠に見える — このページが避けている失敗そのもの。
//
// ## なぜ載せるのか
//
// 11語のうち `しぼりたて` と `ひやおろし` は**実際にスペック欄に書かれて集計に入る**のに、
// 「告示に定義を確認できていない」としか書いていなかった。読み手にとっては
// 「では何なのか」が残る。**法令に無い＝説明できない、ではない**ので、
// 慣習であることを明示したうえで、いつ出回る何を指す語なのかを書く。
//
// ## 書かないこと
//
// - **時期を断定しない。** 蔵や地域で1〜2か月ずれる。「おおむね」を落とさない
// - **味の優劣を書かない**（「新酒はフレッシュで美味い」の類）。呼び名の説明に徹する
// - **このアプリはこの語で何も判定していない**（季節で絞り込む機能は無い）

export type SeasonalTerm = {
  readonly term: string
  /** おおむね出回る時期。**幅で書く**（月を1つに決めない） */
  readonly season: string
  /** どういう酒を指す呼び名か。製法の一般解説には踏み込まない */
  readonly meaning: string
}

