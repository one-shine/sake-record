// 銘柄名を照合キーに落とす。ログの表記とさけのわの銘柄名は「同じ酒なのに文字列が一致しない」
// ことが多いので、突き合わせる両側をこの関数に通してから比較する
// (src/data/brand-aliases.ts の label も正規化済みの値で書いてある)。
//
// 手順は NFKC → 括弧内除去 → 空白除去 → 異体字を新字体へ → lowercase。
// 203本での紐付け実測値(auto 173 / エイリアス込み 186)はこの手順とこの異体字マップ込みの値なので、
// 手順や収録字を変えると linkBrand の回帰スナップショットが動く。

/**
 * NFKC が畳まない異体字 → 新字体。**このマップが無いと 髙/寫/冨 は別字のまま残る**
 * (`髙砂` と `高砂`、`寫楽` と `写楽` は NFKC 後も等しくならない。これがマップの存在理由)。
 *
 * 収録字は203本のログとさけのわマスタ(brands 3264 / breweries 1749)を突き合わせて決めた。
 * 同梱データとログのどちらにも1件も出現しないのは `惠` `舘` `嵜` `碕` の4字だけで、
 * これらは手入力の銘柄名(Phase 4 のサジェスト)と月次更新で入ってくる側に備えて残している。
 * 追加・削除するときは normalize.test.ts の期待表と件数を一緒に更新すること。
 */
export const VARIANT_CHARS: Readonly<Record<string, string>> = {
  髙: '高', // ログ `髙砂` / 蔵元 `髙千代酒造`
  寫: '写', // ログ `寫楽`(5本)。さけのわ未登録なので紐付かないが照合キーは揃える
  冨: '富', // ログと銘柄 `栄光冨士` / 蔵元 `冨士酒造`
  澤: '沢', // 銘柄 `丹澤山` と `丹沢山`(同一県内の表記ゆれ)
  嶋: '島', // 銘柄 `濱嶋` `敷嶋` / 蔵元 `小嶋総本店`
  邊: '辺', // 蔵元 `渡邊佐平商店`
  邉: '辺', // 蔵元 `渡邉酒造`
  瀧: '滝', // 銘柄 `幻の瀧` `瀧嵐`
  眞: '真', // 銘柄 `丸眞正宗`
  惠: '恵', // 同梱データには出現しない(手入力・月次更新に備える)
  龍: '竜', // ログ `龍吟虎嘯` / 銘柄37件
  國: '国', // 銘柄 `両國` / 蔵元 `國暉酒造`
  壽: '寿', // `磐城壽`(福島) と `磐城寿`(山形) — 県を跨ぐ唯一の衝突。都道府県で解ける
  濱: '浜', // 銘柄 `外ヶ濱` `濱嶋` / 蔵元 `濱田酒造`
  巖: '巌', // 銘柄 `巖` `巖乃泉`
  齊: '斉', // 蔵元 `齊藤酒造`
  齋: '斎', // 銘柄/蔵元 `齋彌酒造`
  寶: '宝', // 銘柄 `天寶一`
  舘: '館', // 同梱データには出現しない(同上)
  嵜: '崎', // 同梱データには出現しない(同上)
  碕: '崎', // 同梱データには出現しない(同上)
}

// 文字クラスはマップのキーから組む。列挙を2箇所に書くと必ずドリフトする。
const VARIANT_RE = new RegExp(`[${Object.keys(VARIANT_CHARS).join('')}]`, 'gu')

// 括弧の中身は商品名・シリーズ名・注記であって銘柄名ではない
// (`寒菊(OCEAN99)` `翔空(Lagoon Brewery)` `ゆきのまゆ（醸す森）` `御湖鶴（旧）`)。
// 全角 （） ［］ は NFKC が半角へ畳むのでこの正規表現には届かない(test で固定)。
// 隅付き 【】 は NFKC が畳まないので自前の枝を持つ。
const BRACKETED_RE = /\([^()]*\)|\[[^[\]]*\]|【[^【】]*】/gu

function stripBracketed(s: string): string {
  // 入れ子 `A(B(C))` は1回の置換だと内側だけが消えて `A(B)` が残る。変化しなくなるまで回す。
  // 対応する閉じ括弧が無い場合は消さない(銘柄名を丸ごと落とすより残したほうが害が小さい)。
  let out = s
  for (;;) {
    const next = out.replace(BRACKETED_RE, '')
    if (next === out) return out
    out = next
  }
}

export function normalize(s: string): string {
  return stripBracketed(s.normalize('NFKC'))
    .replace(/\s+/gu, '')
    .replace(VARIANT_RE, (ch) => VARIANT_CHARS[ch])
    .toLowerCase()
}
